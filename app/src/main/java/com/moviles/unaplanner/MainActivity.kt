import com.moviles.unaplanner.notifications.NotificationHelper
import com.moviles.unaplanner.ui.theme.UNAPLANNERTheme

class MainActivity : ComponentActivity() {

    private val requestNotificationPermission =
        registerForActivityResult(ActivityResultContracts.RequestPermission()) { }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()

        // Crear el canal antes de cualquier notificación
        NotificationHelper.createChannel(this)

        // Pedir permiso POST_NOTIFICATIONS (Android 13+)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            requestNotificationPermission.launch(Manifest.permission.POST_NOTIFICATIONS)
        }

        setContent {
            UnaPlannerApp()
        }
    }
}

